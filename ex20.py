data = input("Digite o numero do dia da semana (1 a 7): ")
if data == "1":
    print("Domingo")
elif data == "2":
    print("Segunda-feira")
elif data == "3":
    print("Terça-feira")
elif data == "4":
    print("Quarta-feira")
elif data == "5":
    print("Quinta-feira")
elif data == "6":
    print("Sexta-feira")
elif data == "7":
    print("Sábado")
else:
    print("Número inválido")